function cable(id, projectId, name, code, type, fromNodeId, toNodeId, path, extra = {}) {
  const colorByType = {
    backbone: '#22d3ee',
    feeder: '#a3e635',
    distribution: '#f59e0b',
    drop: '#f472b6',
  };
  return {
    id,
    projectId,
    name,
    code,
    type,
    fromNodeId,
    toNodeId,
    path,
    color: colorByType[type],
    animation: { type: type === 'backbone' ? 'flow' : type === 'feeder' ? 'flow' : 'pulse', speed: 1, reverse: false },
    status: 'active',
    fiberCount: type === 'backbone' ? 48 : type === 'feeder' ? 24 : type === 'distribution' ? 12 : 1,
    usedFibers: type === 'backbone' ? 12 : type === 'feeder' ? 8 : type === 'distribution' ? 5 : 1,
    lengthM: Math.round(pathLength(path)),
    notes: '',
    createdAt: daysAgo(14),
    updatedAt: now(),
    ...extra,
  };
}

